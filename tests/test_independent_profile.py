"""Original-rule parity, real provider adaptation and no partial fusion."""
import copy
import json
from pathlib import Path
from types import ModuleType
import unittest
from unittest.mock import patch

from luckypath.analysis_input import prepare_input
from luckypath.independent_profile import build_independent_profile
from luckypath.route_maker_reading import (
    CONFIG, EVENTS, QUALITIES, STREETS, ROUTING_AXES, branch_interactions,
    combine_scores, compatibility_profile, find_aspects, interpret_astrology,
    interpret_saju, load_rules, provenance, routing_projection, street_weights,
)


BASE = {"birth_date": "1990-05-15", "birth_time": "14:30",
        "birth_timezone": "Asia/Seoul", "target_date": "2026-10-17"}
REFERENCE = json.loads((Path(__file__).parent / "fixtures/route_maker_reference.json").read_text())


class OriginalRuleTests(unittest.TestCase):
    def test_golden_results_match_original_engine_not_the_old_five_axis_average(self):
        # The fixture was generated by the original engine from invented raw
        # signals. It includes independent saturation, mean and full matrix.
        for case in REFERENCE["cases"]:
            with self.subTest(case=case["name"]):
                s = interpret_saju(case["raw_saju"], load_rules(CONFIG / "saju_rules.csv")).result()
                a = interpret_astrology(case["raw_astrology"], load_rules(CONFIG / "astrology_rules.csv")).result()
                self.assertEqual(s, case["expected"]["saju"])
                self.assertEqual(a, case["expected"]["astrology"])
                combined = combine_scores(s, a)
                self.assertEqual(combined, case["expected"]["combined"])
                full = street_weights(combined["quality"])
                self.assertEqual(full, case["expected"]["source_street_weights"])
                self.assertEqual(set(full), set(STREETS))
                projected = routing_projection(full)
                self.assertEqual(set(projected), set(ROUTING_AXES))
                self.assertAlmostEqual(sum(projected.values()), 1, places=14)
                for axis in ROUTING_AXES:
                    self.assertEqual(projected[axis], full[axis] / sum(full[key] for key in ROUTING_AXES))
                # A mean after each source's matrix normalization is different.
                sw, aw = street_weights(s["quality"]), street_weights(a["quality"])
                wrong_stage = {key: round((sw[key] + aw[key]) / 2, 4) for key in STREETS}
                self.assertNotEqual(full, wrong_stage)

    def test_aspects_match_original_strength_orb_order_and_top_six(self):
        case = REFERENCE["aspect_case"]
        self.assertEqual(find_aspects(case["transit"], case["natal"]), case["expected"])
        raw = REFERENCE["cases"][0]["raw_astrology"]
        result = interpret_astrology(raw, load_rules(CONFIG / "astrology_rules.csv"))
        planet_rows = [item for item in result.evidence if item["signal_type"] == "planet"]
        self.assertEqual(len(planet_rows), 12)  # two contributions per retained aspect
        self.assertNotIn("uranus", {item["signal"] for item in planet_rows})
        self.assertEqual(planet_rows[1]["strength"], raw["aspects"][0]["strength"] * .5)

    def test_branch_pair_bug_is_corrected_in_both_directions(self):
        for kind, pairs in (("combination", ("子丑", "寅亥", "卯戌", "辰酉", "巳申", "午未")),
                            ("clash", ("子午", "丑未", "寅申", "卯酉", "辰戌", "巳亥"))):
            for pair in pairs:
                for natal, today in (pair, reversed(pair)):
                    with self.subTest(kind=kind, natal=natal, today=today):
                        result = branch_interactions({"year": {"branch": natal}}, today)
                        self.assertEqual([row["type"] for row in result], [kind])
        self.assertEqual(branch_interactions({"day": {"branch": "子"}}, "子"), [])

    def test_rule_files_are_unchanged_and_matrix_never_hides_unsupported_axes(self):
        meta = provenance()
        self.assertTrue(meta["source_rules_unchanged"])
        self.assertFalse(meta["externally_validated"])
        self.assertEqual(len(meta["rule_files"]), 3)
        weights = REFERENCE["cases"][0]["expected"]["source_street_weights"]
        original = copy.deepcopy(weights)
        projected = routing_projection(weights)
        display = compatibility_profile({"status": "ready", "routing_weights": projected,
                                         "source_street_weights": weights, "evidence": []}, combined=True)
        self.assertEqual(weights, original)
        self.assertEqual(display["routing_weights"], projected)
        self.assertEqual(display["profile_scores"]["access"], 5)
        self.assertEqual(max(display["profile_scores"].values()), 10)
        self.assertEqual(display["policy"]["stage"], "after_independent_event_quality_before_street_matrix")
        self.assertEqual(display["policy"]["system_weights"], {"saju": .5, "astrology": .5})
        self.assertEqual(display["source_street_weights"], weights)


class IndependentProfileTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        from luckypath.saju_analysis import analyze_saju
        from luckypath.astrology_analysis import analyze_astrology
        context = prepare_input(BASE)
        cls.facts = {"saju": analyze_saju(context), "astrology": analyze_astrology(context)}

    def modules(self, contexts=None):
        contexts = contexts if contexts is not None else []
        modules = {}
        for system in ("saju", "astrology"):
            module = ModuleType(system)
            def analyze(context, system=system):
                self.assertNotIn("analysis", context)
                self.assertNotIn("profile", context)
                contexts.append(copy.copy(context))
                return self.facts[system]
            setattr(module, "analyze_" + system, analyze)
            modules["luckypath." + system + "_analysis"] = module
        return modules

    def test_factual_sources_stay_separate_and_combined_quality_precedes_street_matrix(self):
        contexts, original = [], copy.deepcopy(self.facts)
        with patch.dict("sys.modules", self.modules(contexts)):
            result = build_independent_profile(BASE)
        self.assertEqual(contexts[0], contexts[1])
        self.assertEqual(self.facts, original)
        self.assertEqual(result["schema_version"], 2)
        self.assertEqual(result["profile_version"], "route-maker-reading-v1")
        self.assertEqual(result["profile_status"], "ready")
        reading = result["route_maker_reading"]
        self.assertEqual(set(reading["combined"]["event"]), set(EVENTS))
        self.assertEqual(set(reading["combined"]["quality"]), set(QUALITIES))
        self.assertEqual(reading["combined"], combine_scores(reading["saju"], reading["astrology"]))
        self.assertEqual(reading["source_street_weights"], street_weights(reading["combined"]["quality"]))
        self.assertEqual(result["combined"]["routing_weights"], reading["routing_weights"])
        self.assertEqual({item["source"] for item in reading["coverage"]["omitted"]},
                         {"water", "sunlight", "rest", "culture"})
        self.assertNotIn("profile_scores", result)
        self.assertNotIn("natal", result)
        self.assertEqual(reading["sources"]["astrology"]["provider"]["data"]["origin"], "NASA/JPL DE440s")
        json.dumps(result, allow_nan=False)

    def test_failed_provider_never_becomes_a_partial_blend_or_leaks_error_details(self):
        modules = self.modules()
        def failure(_):
            raise RuntimeError("private-birth-canary /Users/private")
        modules["luckypath.astrology_analysis"].analyze_astrology = failure
        with patch.dict("sys.modules", modules):
            result = build_independent_profile(BASE)
        self.assertEqual(result["profile_status"], "unavailable")
        self.assertIsNone(result["combined"])
        self.assertEqual(result["systems"]["saju"]["profile"]["status"], "ready")
        self.assertEqual(result["route_maker_reading"]["saju"]["status"], "ready")
        self.assertEqual(result["systems"]["astrology"]["status"], "error")
        self.assertNotIn("private-birth-canary", json.dumps(result))

    def test_old_five_score_only_or_malformed_provider_cannot_silently_apply(self):
        modules = self.modules()
        for invalid in (None, [], {"profile": {"status": "ready"}}, {"analysis": {}},
                        {"analysis": {"natal": None}}, {"analysis": {"natal": {"planets": {}}}}):
            with self.subTest(invalid=invalid):
                modules["luckypath.astrology_analysis"].analyze_astrology = lambda _, value=invalid: value
                with patch.dict("sys.modules", modules):
                    result = build_independent_profile(BASE)
                self.assertIsNone(result["combined"])
                self.assertEqual(result["systems"]["astrology"]["status"], "error")
                json.dumps(result, allow_nan=False)

    def test_unknown_birth_time_omits_personal_transits_without_inventing_noon(self):
        result = build_independent_profile({**BASE, "birth_time": None})
        self.assertEqual(result["profile_status"], "ready")
        reading = result["route_maker_reading"]
        self.assertEqual(reading["astrology"]["interpreted_aspects"], [])
        self.assertTrue(reading["astrology"]["omissions"])
        self.assertTrue(reading["saju"]["omissions"])
        self.assertEqual({item["signal_type"] for item in reading["astrology"]["evidence"]}, {"element"})
        self.assertIsNone(result["systems"]["astrology"]["analysis"]["natal"]["planets"]["Sun"]["longitude_deg"])


if __name__ == "__main__":
    unittest.main()
